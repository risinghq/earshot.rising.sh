import { describe, expect, it } from "vitest";
import { qrMatrix } from "../src/play/room/qr";

// The expected symbol is segno 1.6.6's output for this URL at level M,
// mask 5, so the encoder's data, error correction and placement are all
// checked against a reference implementation.
const expected = [
  "11111110000101110010101111111",
  "10000010111110001100101000001",
  "10111010111100101011101011101",
  "10111010100110011100101011101",
  "10111010000010000001101011101",
  "10000010010101001110001000001",
  "11111110101010101010101111111",
  "00000000100000001001100000000",
  "10000010111110100101011001110",
  "10000101011010110111000110110",
  "01111111010111011010111100000",
  "01010000100110111010000011000",
  "10101011110001001010101000001",
  "00110000101010011111101110011",
  "10010110010010111100101001100",
  "11000000010000110001110010101",
  "01000110011000100100100101100",
  "10010001110100011001111110111",
  "11101010101101011111001011001",
  "10111001001100110010000010000",
  "10011010000010111101111110111",
  "00000000111110110110100011000",
  "11111110000111111001101011100",
  "10000010001100011011100010001",
  "10111010010101101001111111010",
  "10111010000100010010100001101",
  "10111010001000111010011111110",
  "10000010001011001001010111101",
  "11111110110111101101011110100",
];

describe("qr", () => {
  it("encodes the join link as the reference QR matrix", () => {
    const matrix = qrMatrix("https://earshot.rising.sh/play/room/ABCDEF");
    expect(
      matrix.map((row) => row.map((cell) => (cell ? "1" : "0")).join("")),
    ).toEqual(expected);
  });
});
